"""
PDF report generation.

Every string is drawn through services.text_shaper, which routes Latin
text to a registered Noto Sans TTF and Devanagari / other complex
scripts through HarfBuzz before emitting vector glyph outlines. That
means Marathi and Hindi (and user-supplied names in any of them) print
correctly -- conjuncts, half-forms, reph and reordered matras -- which
ReportLab's built-in Type1 fonts cannot do at all.
"""
import io
from datetime import datetime

from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import cm
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.platypus import (
    SimpleDocTemplate, Spacer, Table, TableStyle,
    HRFlowable, KeepTogether, PageBreak,
)

from models.schemas import AssessmentResponse
from services.text_shaper import P, string_width

PRIMARY = colors.HexColor('#0d5c8c')
SECONDARY = colors.HexColor('#27ae60')
ACCENT = colors.HexColor('#e8f4fd')
GREY = colors.HexColor('#6c757d')
LIGHT_GREY = colors.HexColor('#f8f9fa')
WARN = colors.HexColor('#b45309')
WARN_BG = colors.HexColor('#fff7ed')

MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
          'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

_HEADER = 'Integrated Intelligent Assessment Report'
_FOOTER = ('Report generated by HYDRO RAIN GUARD | ICICIS Conference 2026 | '
           'JSPM Rajarshi Shahu College of Engineering, Pune')


def _v(value):
    """Enum -> its plain string value (avoids 'RoofType.RCC' in output)."""
    return getattr(value, 'value', value)


def _dims(d: dict) -> str:
    """Prettify the dimensions dict: volume_m3 -> 'volume (m³)'."""
    units = {'m3': 'm³', 'm2': 'm²'}
    out = []
    for k, v in d.items():
        label = k.replace('_', ' ')
        for a, b in units.items():
            if label.endswith(' ' + a):
                label = f"{label[:-len(a) - 1]} ({b})"
        out.append(f"{label}: {v}")
    return '  |  '.join(out)


def _payback_text(years):
    """Render the payback period, including the "never" case."""
    if years is None:
        return "Not viable"
    return f"{years:.1f}"


def _h(text, space_before=16):
    return P(text, 13, True, PRIMARY, space_before=space_before, space_after=8)


def _th(text, align='left'):
    """Table header cell."""
    return P(text, 9, True, colors.white, align)


def _td(text, align='left', bold=False):
    return P(text, 9, bold, colors.black, align)


def _kv_table(rows, col_widths, head_color=SECONDARY, key_bold=True):
    """Key-value table with a coloured header row and zebra striping.

    Every cell is a ShapedParagraph so Devanagari renders correctly.
    """
    data = [[_th(c, 'left' if i == 0 else 'right')
             for i, c in enumerate(rows[0])]]
    for r in rows[1:]:
        row = [P(str(r[0]), 9, key_bold, colors.black, 'left')]
        row += [P(str(c), 9, False, colors.black, 'right') for c in r[1:]]
        data.append(row)

    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), head_color),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#c9ced3')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, LIGHT_GREY]),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
    ]))
    return t


def _on_page(canvas, doc):
    """Running footer with page number on every page."""
    canvas.saveState()
    canvas.setStrokeColor(colors.HexColor('#d0d7de'))
    canvas.setLineWidth(0.4)
    canvas.line(2 * cm, 1.55 * cm, A4[0] - 2 * cm, 1.55 * cm)
    P(f"Page {canvas.getPageNumber()}", 7.5, False, GREY, 'right').drawOn(
        canvas, A4[0] - 5.2 * cm, 1.05 * cm)
    P(_FOOTER, 6.8, False, GREY).drawOn(canvas, 2 * cm, 1.05 * cm)
    canvas.restoreState()


def generate_pdf_report(assessment: AssessmentResponse) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=2 * cm,
        leftMargin=2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
        title="HydroRainGuard Assessment Report",
        author="HydroRainGuard",
        subject="Rainwater harvesting feasibility assessment",
    )

    story = []
    req = assessment.request
    w = assessment.weather
    r = assessment.runoff
    rc = assessment.recharge
    cb = assessment.cost_benefit
    hg = assessment.hydrogeo_info

    # ── TITLE ──────────────────────────────────────────────────────
    story.append(Spacer(1, 0.8 * cm))
    story.append(P('HYDRO RAIN GUARD', 22, True, PRIMARY, 'center', space_after=6))
    story.append(P('Integrated Intelligent Assessment Report', 11, False, GREY,
                   'center', space_after=3))
    story.append(P('Rainwater Harvesting & Artificial Groundwater Recharge',
                   10, False, GREY, 'center', space_after=14))
    story.append(HRFlowable(width='100%', thickness=2, color=PRIMARY))
    story.append(Spacer(1, 0.4 * cm))

    meta_rows = [
        ['Field', 'Value'],
        ['Project / Owner', req.name],
        ['Location', str(req.location)],
        ['Coordinates', f"{req.latitude:.4f}, {req.longitude:.4f}"],
        ['Sampled near grid cell', w.grid_cell or 'n/a'],
        ['Report generated', datetime.now().strftime('%d %B %Y, %H:%M')],
        ['Assessment ID', assessment.assessment_id],
        ['Rainfall source', w.rainfall_source or 'n/a'],
    ]
    story.append(_kv_table(meta_rows, [5 * cm, 11 * cm], PRIMARY))
    story.append(Spacer(1, 0.4 * cm))

    # ── EXECUTIVE SUMMARY ──────────────────────────────────────────
    story.append(_h('Executive Summary', space_before=6))
    summary_rows = [
        ['Metric', 'Value', 'Unit'],
        ['Annual rooftop runoff', f"{r.annual_runoff_volume/1000:,.1f}", 'KL/year'],
        ['Harvestable volume', f"{r.harvestable_volume/1000:,.1f}", 'KL/year'],
        ['Groundwater recharge potential', f"{rc.annual_recharge_potential/1000:,.1f}", 'KL/year'],
        ['Recharge feasibility score', f"{rc.recharge_feasibility_score:.0f}", '/ 100'],
        ['Annual water cost savings', f"{cb.annual_savings_inr:,.0f}", 'INR/year'],
        ['Groundwater recharge value', f"{cb.annual_recharge_value_inr:,.0f}", 'INR/year'],
        ['Estimated installation cost', f"{cb.estimated_cost:,.0f}", 'INR'],
        ['Payback period', _payback_text(cb.payback_period_years), 'Years'],
        ['10-year ROI', f"{cb.roi_percentage:.1f}", '%'],
    ]
    story.append(_kv_table(summary_rows, [9 * cm, 4 * cm, 3 * cm], PRIMARY,
                           key_bold=False))

    # ── RAINFALL DATA (provenance) ─────────────────────────────────
    story.append(_h('Rainfall Data & Provenance'))
    rain_rows = [
        ['Item', 'Value'],
        ['Dataset', w.rainfall_source or 'n/a'],
        ['Method', w.rainfall_method or 'n/a'],
        ['Climatology period', w.climatology_period or 'n/a'],
        ['Grid resolution', f"{w.grid_resolution_deg:g}°" if w.grid_resolution_deg else 'n/a'],
        ['Interpolated from', w.grid_cell or 'n/a'],
        ['Annual total', f"{w.annual_rainfall:,.0f} mm"],
        ['Wettest month', f"{MONTHS[max(range(12), key=lambda i: w.monthly_rainfall[i])]} "
                          f"({max(w.monthly_rainfall):,.0f} mm)"],
        ['Driest month', f"{MONTHS[min(range(12), key=lambda i: w.monthly_rainfall[i])]} "
                         f"({min(w.monthly_rainfall):,.0f} mm)"],
    ]
    story.append(_kv_table(rain_rows, [4.5 * cm, 11.5 * cm], SECONDARY))
    story.append(Spacer(1, 0.25 * cm))

    if w.rainfall_is_grid_estimate:
        story.append(P(
            'Note: the annual total above comes straight from the gridded '
            'climatology. At 2.5° a cell is roughly 278 km across, so it '
            'cannot resolve local orographic gradients — for example the '
            'Western Ghats escarpment, where a single cell spans both the '
            'high-rainfall crest and the much drier rain-shadow to its east. '
            'Where a local station total is known (IMD, state groundwater '
            'board, or a rain gauge on site), re-run the assessment with '
            'that figure as the annual override: the monthly distribution '
            'is kept and only the total is rescaled.',
            8, False, WARN, space_after=4))
        note = Table([[P('Grid estimate — local override recommended if available',
                         8.5, True, WARN)]], colWidths=[16 * cm])
        note.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), WARN_BG),
            ('BOX', (0, 0), (-1, -1), 0.6, WARN),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(note)

    # ── INPUT PARAMETERS ───────────────────────────────────────────
    story.append(_h('Input Parameters'))
    input_rows = [
        ['Parameter', 'Value'],
        ['Roof type', str(_v(req.roof_type))],
        ['Roof area', f"{req.roof_area:,.0f} m²"],
        ['Occupants', str(req.num_people)],
        ['Open space area', f"{req.open_space_area:,.0f} m²"],
        ['Soil type', str(_v(req.soil_type))],
        ['Groundwater depth', f"{req.groundwater_depth:,.1f} m"],
        ['Annual rainfall', f"{w.annual_rainfall:,.0f} mm"],
        ['Runoff coefficient (C)', f"{r.runoff_coefficient:.2f}"],
        ['Curve number (CN)', f"{r.curve_number:.0f}"],
        ['Soil infiltration rate', f"{rc.infiltration_rate:,.1f} mm/hr"],
    ]
    story.append(_kv_table(input_rows, [8 * cm, 8 * cm], SECONDARY))

    # ── MONTHLY RAINFALL & RUNOFF ──────────────────────────────────
    story.append(PageBreak())
    story.append(_h('Monthly Rainfall & Runoff', space_before=0))
    method_label = (
        'Rational / volumetric (Q = C × R × A, CGWB 2007)'
        if r.runoff_method == 'rational'
        else 'SCS Curve Number (USDA-NRCS TR-55)'
    )
    story.append(P(
        f"Primary method: {method_label}. "
        f"C = {r.runoff_coefficient:.2f}, CN = {r.curve_number:.0f}. "
        f"The SCS-CN column is reported as a cross-check: run on monthly "
        f"totals it differs from the Rational method by "
        f"{r.scs_cn_vs_rational_pct:+.0f}%, which is the expected spread "
        f"between the two approaches.",
        8.5, False, GREY, space_after=8))

    monthly_rows = [['Month', 'Rainfall\n(mm)', 'Runoff\n(L)',
                     'SCS-CN\n(L)', 'Savings\n(INR)']]
    for i, m in enumerate(MONTHS):
        monthly_rows.append([
            m,
            f"{w.monthly_rainfall[i]:,.1f}",
            f"{r.monthly_runoff[i]:,.0f}",
            f"{r.scs_cn_monthly_runoff[i]:,.0f}" if r.scs_cn_monthly_runoff else '—',
            f"{cb.monthly_savings[i]:,.0f}",
        ])
    monthly_rows.append([
        'ANNUAL',
        f"{w.annual_rainfall:,.0f}",
        f"{r.annual_runoff_volume:,.0f}",
        f"{r.scs_cn_annual_runoff:,.0f}",
        f"{cb.annual_savings_inr:,.0f}",
    ])

    data = [[_th(c, 'right' if i else 'left') for i, c in enumerate(monthly_rows[0])]]
    for i, row in enumerate(monthly_rows[1:]):
        last = i == len(monthly_rows) - 2
        data.append([
            P(row[0], 8, last, colors.black, 'left'),
            P(row[1], 8, last, colors.black, 'right'),
            P(row[2], 8, last, colors.black, 'right'),
            P(row[3], 8, last, colors.black, 'right'),
            P(row[4], 8, last, colors.black, 'right'),
        ])
    mt = Table(data, colWidths=[3.2 * cm, 3.2 * cm, 3.2 * cm, 3.2 * cm, 3.2 * cm],
               repeatRows=1)
    mt.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), PRIMARY),
        ('BACKGROUND', (0, -1), (-1, -1), colors.HexColor('#e8f5e9')),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#c9ced3')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -2), [colors.white, ACCENT]),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
    ]))
    story.append(mt)

    # ── GROUNDWATER RECHARGE ───────────────────────────────────────
    story.append(_h('Groundwater Recharge Assessment'))
    rech_rows = [
        ['Parameter', 'Value'],
        ['Aquifer type', rc.aquifer_type],
        ['Groundwater depth', f"{req.groundwater_depth:,.1f} m"],
        ['Soil infiltration rate', f"{rc.infiltration_rate:,.1f} mm/hr"],
        ['Annual recharge potential', f"{rc.annual_recharge_potential/1000:,.1f} KL/year"],
        ['Daily recharge rate', f"{rc.groundwater_recharge_rate:,.0f} L/day"],
        ['Recharge feasibility score', f"{rc.recharge_feasibility_score:.0f} / 100"],
        ['Aquifer permeability', hg.permeability],
        ['Groundwater quality', str(_v(hg.groundwater_quality))],
        ['Seasonal fluctuation', f"{hg.seasonal_fluctuation:,.1f} m"],
        ['Aquifer depth', f"{hg.aquifer_depth:,.1f} m"],
        ['Transmissivity', f"{hg.transmissivity:,.1f} m²/day"],
        ['Storage coefficient', f"{hg.storage_coefficient:.3f}"],
    ]
    story.append(_kv_table(rech_rows, [8 * cm, 8 * cm], SECONDARY))

    # ── RECOMMENDED STRUCTURES ─────────────────────────────────────
    story.append(_h('Recommended Structures'))
    story.append(P(
        'Ranked by Analytic Hierarchy Process (Saaty, 1980) — a weighted, '
        'consistency-checked multi-criteria score. This is a deterministic '
        'rule-based model, not machine learning.',
        8.5, False, GREY, space_after=8))

    if assessment.mcda:
        m = assessment.mcda
        crit_rows = [['Criterion', 'Weight']]
        pretty = {
            'harvestable_yield': 'Harvestable yield',
            'annual_rainfall': 'Annual rainfall',
            'soil_infiltration': 'Soil infiltration',
            'open_space': 'Open space',
            'groundwater_depth': 'Groundwater depth',
        }
        for k, v in m.weights.items():
            crit_rows.append([pretty.get(k, k), f"{v*100:.1f}%"])
        crit_rows.append(['Consistency ratio (CR)', f"{m.consistency_ratio:.3f}"])
        ct = _kv_table(crit_rows, [10 * cm, 6 * cm], colors.HexColor('#475569'))
        story.append(ct)
        story.append(P(
            f"CR = {m.consistency_ratio:.3f} (λmax = {m.lambda_max:.3f}). "
            f"Saaty's acceptability threshold is 0.10, so the pairwise "
            f"judgements are {'consistent' if m.consistent else 'INCONSISTENT — review the matrix'}.",
            7.5, False, GREY, space_after=8))

    for i, s in enumerate(assessment.recommended_structures[:3], 1):
        head = Table([[
            P(f"#{i}  {s.structure_type}", 10, True, PRIMARY),
            P(f"{s.suitability_score:.0f} / 100", 10, True, PRIMARY, 'right'),
        ]], colWidths=[13 * cm, 3 * cm])
        head.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), ACCENT),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))

        body = [head]
        if s.criteria:
            crit_cells = [[
                P(pretty_of(c), 7.5, True, colors.white)
                for c in s.criteria
            ], [
                P(f"{c.normalised:.2f}", 8, False, colors.black) for c in s.criteria
            ]]
            ctab = Table(crit_cells, colWidths=[3.2 * cm] * len(s.criteria))
            ctab.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#64748b')),
                ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor('#c9ced3')),
                ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
                ('TOPPADDING', (0, 0), (-1, -1), 3),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ]))
            body.append(ctab)

        dims = _dims(s.dimensions)
        rows = [
            [P(s.description, 8.5)],
            [P(f"Dimensions — {dims}", 8, True)],
            [P(f"Installation — {s.installation_notes}", 8)],
        ]
        rt = Table(rows, colWidths=[16 * cm])
        rt.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor('#c9ced3')),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))
        body.append(rt)
        body.append(Spacer(1, 0.3 * cm))
        story.append(KeepTogether(body))

    # ── COST BENEFIT ───────────────────────────────────────────────
    story.append(_h('Cost-Benefit Analysis'))
    cb_rows = [
        ['Item', 'Amount (INR)'],
        ['Total installation cost', f"{cb.estimated_cost:,.0f}"],
        ['  Storage structures', f"{cb.storage_cost:,.0f}"],
        ['  Recharge structures', f"{cb.recharge_cost:,.0f}"],
        ['  Plumbing & conveyance', f"{cb.plumbing_cost:,.0f}"],
        ['Annual water savings (volume)', f"{cb.annual_water_savings_liters/1000:,.1f} KL"],
        ['Annual cost savings', f"{cb.annual_savings_inr:,.0f}"],
        ['Groundwater recharge value', f"{cb.annual_recharge_value_inr:,.0f}"],
        ['Annual maintenance (2%)', f"{cb.annual_maintenance_inr:,.0f}"],
        ['Net annual savings', f"{cb.net_annual_savings_inr:,.0f}"],
        ['Water tariff assumption', f"{cb.water_tariff_per_kl:,.1f} / KL"],
        ['Payback period', _payback_text(cb.payback_period_years) + ' years'],
        ['10-year ROI', f"{cb.roi_percentage:.1f}%"],
    ]
    story.append(_kv_table(cb_rows, [10 * cm, 6 * cm], PRIMARY))

    # ── METHODS & ASSUMPTIONS ──────────────────────────────────────
    story.append(_h('Methods & Assumptions'))
    story.append(P(
        'Rainfall — gridded monthly climatology, bilinearly interpolated '
        'between the four surrounding grid cells; no-data cells are '
        'excluded from the interpolation. '
        'Runoff — Rational / volumetric method (Q = C × R × A) with the '
        'SCS Curve Number method reported as a cross-check; both are '
        'standard, published methods, not fitted models. '
        'First flush — 2 mm discarded per rain event, assumed 100 events '
        'per year. '
        "Recharge — infiltration limited by the soil's saturated "
        "hydraulic conductivity and capped at the rainfall actually "
        "falling on the open area. "
        'Economics — capital cost from unit rates, 2% of capital per year '
        'for maintenance, savings valued at the water tariff stated '
        'above; no discount rate is applied to the payback figure. '
        'Structure ranking — Analytic Hierarchy Process, a deterministic '
        'weighted scoring method; it is not machine learning and uses '
        'no training data.',
        8, False, GREY))
    story.append(P(
        'Screening-level estimates only. Verify against a site-specific '
        'hydrogeological investigation before construction.',
        8, True, WARN, space_before=6))

    story.append(Spacer(1, 0.4 * cm))
    story.append(HRFlowable(width='100%', thickness=1, color=GREY))
    story.append(P(
        'All figures are engineering estimates for pre-feasibility screening. '
        'Verify against site-specific investigation before construction.',
        7, False, GREY, 'center', space_before=6))

    doc.build(story, onFirstPage=_on_page, onLaterPages=_on_page)
    buffer.seek(0)
    return buffer.read()


_CRITERIA_PRETTY = {
    'harvestable_yield': 'Yield',
    'annual_rainfall': 'Rainfall',
    'soil_infiltration': 'Soil',
    'open_space': 'Space',
    'groundwater_depth': 'Depth',
}


def pretty_of(c) -> str:
    """Short label for an AHP criterion, used as a table header."""
    name = getattr(c, 'name', c)
    return _CRITERIA_PRETTY.get(name, str(name).replace('_', ' ').title())
